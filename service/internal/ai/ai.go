package ai

import (
	"quikram-service/internal/models"
)

type LLMProvider interface {
	GenerateSummary(text, level string) (string, error)
	GenerateQuiz(summaryText string, count int, difficulty string) ([]models.Question, error)
	ChatCompletion(messages []models.ChatMessage, systemContext string) (string, error)
}

func GeneratePrompt(level string) string {
	switch level {
	case "short":
		return `Напиши краткий конспект текста на русском языке. Конспект должен быть логически связным, охватывать главные мысли, но в сжатой форме — примерно треть от полного объёма. Раздели на 3 смысловых блока, каждому дай короткий заголовок с новой строки. Заголовки пиши обычным текстом, без символов вроде **, #, *.

Требования:
- Только русский язык
- Без markdown-разметки
- Без комментариев и пояснений
- Текст конспекта, ничего лишнего

Текст:
`
	case "medium":
		return `Напиши конспект текста среднего размера на русском языке. Конспект должен быть логически связным, раскрывать основные темы и идеи, содержать ключевые термины и примеры. Раздели на разделы с заголовками, между разделами пустая строка. Заголовки пиши обычным текстом, без символов вроде **, #, *.

Требования:
- Только русский язык
- Без markdown-разметки
- Без комментариев и пояснений

Текст:
`
	case "long":
		return `Напиши подробный конспект текста на русском языке. Сохрани все разделы, примеры, термины, определения, аргументы. Конспект должен быть логически связным и хорошо структурированным. Каждый раздел с заголовком на отдельной строке, между разделами пустая строка. Заголовки пиши обычным текстом, без символов вроде **, #, *.

Требования:
- Только русский язык
- Без markdown-разметки
- Без комментариев и пояснений

Текст:
`
	}
	return ""
}

func GenerateSystemPrompt() string {
	return "Ты составляешь конспекты на русском языке. Пишешь чистый текст без разметки."
}

func MaxTokensForLevel(level string) int {
	switch level {
	case "short":
		return 2048
	case "medium":
		return 4096
	case "long":
		return 8192
	}
	return 2048
}
